import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import type { AppConfig } from '../config/configuration.js';

// Callers only know "save, read, delete by key", so moving to S3 later means
// writing one new class and changing one provider.
export abstract class StorageService {
  abstract save(key: string, data: Buffer): Promise<void>;
  abstract read(key: string): Promise<Buffer>;
  abstract delete(key: string): Promise<void>;
}

// Keys are UUIDs generated by the server, never user input, so they can't be
// used to reach outside this folder. The API and worker must share the folder.
@Injectable()
export class LocalStorageService extends StorageService {
  private readonly root: string;

  constructor(config: ConfigService<AppConfig, true>) {
    super();
    this.root = resolve(config.get('storageDir', { infer: true }));
  }

  async save(key: string, data: Buffer): Promise<void> {
    await mkdir(this.root, { recursive: true });
    await writeFile(join(this.root, key), data);
  }

  read(key: string): Promise<Buffer> {
    return readFile(join(this.root, key));
  }

  async delete(key: string): Promise<void> {
    await rm(join(this.root, key), { force: true });
  }
}
